PERIOD_COLS = [16, 17, 18, 19]
TOKKI_COL = 20
TOKKI_ROWS = range(11, 41)
ZEIRITSU = 0.30


def build_zaimu(p):
    """1期分の内訳から業況推移表の全コードを整合させて組み立てる。

    自己資本は前期＋税引後利益で繰り上がる（配当なし）。
    貸借を合わせる差額はその他固定資産（投資その他の資産）で吸収する。
    現金で吸収すると流動資産が動いて流動比率が設計値からずれるため。
    """
    z = {}
    # --- PL（先に確定させる。自己資本の繰り上がりに税引後利益を使う）---
    z[740] = p['売上']
    z[750] = round(z[740] / 12)
    z[760] = p['原価']
    z[780] = z[740] - z[760]
    z[790] = round(z[780] / z[740], 3)
    z[800] = p['販管費']
    z[810] = round(z[800] / z[740], 3)
    z[820] = z[780] - z[800]
    z[830] = p['支払利息']
    z[840] = z[820] - z[830] + p.get('営業外純', 0)
    z[850], z[860] = p.get('特利', 0), p.get('特損', 0)
    zeibiki_mae = z[840] + z[850] - z[860]
    z[870] = round(zeibiki_mae * (1 - ZEIRITSU)) if zeibiki_mae > 0 else zeibiki_mae
    z[890], z[900] = p['減価償却'], 0
    z[910], z[920], z[940] = p.get('役員報酬', 0), 0, 0

    # --- 負債 ---
    z[450], z[470], z[490], z[540] = p['支手'], p['買掛'], p['短借'], p['一年内']
    z[560], z[590], z[600] = p.get('他有利子流', 0), 0, 0
    z[601] = p['他流負']
    z[440] = z[450] + z[470] + z[490] + z[540] + z[560] + z[601]
    z[630], z[640] = p['長借'], p.get('他有利子固', 0)
    z[641] = p['他固負']
    z[620] = z[630] + z[640] + z[641]
    z[680] = z[440] + z[620]

    # --- 純資産（前期＋税引後利益。初年度は指定値）---
    z[690] = p['自己資本']
    z[700], z[720] = p['資本金'], p['繰越']
    z[730] = z[490] + z[540] + z[560] + z[630] + z[640]
    z[980] = p.get('劣後', 0)
    z[960] = p.get('割引手形', 0)

    # --- 資産（その他固定資産で貸借の差額を吸収する）---
    z[20] = p['現金']
    z[70], z[80], z[120] = p['受手'], p['売掛'], p['棚卸']
    z[190], z[200], z[210], z[211] = p.get('未収', 0), 0, 0, p.get('他流資', 0)
    z[10] = z[20] + z[70] + z[80] + z[120] + z[190] + z[211]
    z[270], z[280], z[310] = p.get('土地', 0), p.get('建物', 0), p.get('機械', 0)
    z[360], z[370], z[400] = 0, 0, p.get('保険', 0)
    z[401] = (z[680] + z[690]) - z[10] - (z[270] + z[280] + z[310] + z[400])
    z[260] = z[270] + z[280] + z[310] + z[400] + z[401]
    z[420] = 0
    z[430] = z[10] + z[260]

    # --- 指標（カルテの脚注どおり。マイナスは0で書くガードも再現）---
    unten = z[70] + z[80] + z[120] - z[450] - z[470]
    jisshitsu = z[730] - z[980] - unten
    bunbo = z[870] + z[890]
    z[990] = round(z[690] / z[430], 4)
    z[1000] = round(z[10] / z[440], 4)
    z[1010] = round((z[70] + z[80] + z[960]) / z[750], 4)
    z[1020] = round((z[450] + z[470]) / z[750], 4)
    z[1030] = unten
    z[1040] = jisshitsu if jisshitsu > 0 else 0
    z[1050] = round(jisshitsu / bunbo, 2) if (jisshitsu > 0 and bunbo > 0) else 0
    z[1060] = round(z[830] / z[780], 6) if z[780] > 0 else 0

    assert z[430] == z[680] + z[690], f'貸借不一致 {z[430]} != {z[680]}+{z[690]}'
    assert z[401] > 0, f'その他固定資産がマイナス（内訳の置き方が過大）: {z[401]}'
    return z


def periods_of(base, years):
    """4期分を組み立てる。自己資本と繰越利益剰余金を利益で繰り上げる。"""
    out = []
    jiko, kurikoshi = base['自己資本'], base['繰越']
    for i, y in enumerate(years):
        p = {**base, **y, '自己資本': jiko, '繰越': kurikoshi}
        z = build_zaimu(p)
        out.append(p)
        # 次期の期首＝当期末＋当期利益。減資は資本金の振替なので自己資本は動かない
        jiko += z[870]
        kurikoshi += z[870]
    return [build_zaimu(p) and p for p in out]


def code_rows(ws):
    out = {}
    for r in range(1, ws.max_row + 1):
        v = ws.cell(r, 1).value
        if isinstance(v, (int, float)) and float(v) == int(v):
            out[int(v)] = r
    return out


def build(name, masking, periods, entai, hyoshi, gaiyo):
    dst = OUTDIR / name
    shutil.copy(SRC, dst)
    wb = openpyxl.load_workbook(dst)

    for ws in wb.worksheets:
        for row in ws.iter_rows():
            for c in row:
                if isinstance(c.value, str):
                    new = c.value
                    for old, rep in masking.items():
                        new = new.replace(old, rep)
                    if new != c.value:
                        c.value = new

    zs = [build_zaimu(p) for p in periods]
    ws_s = wb['業況推移表']
    rows = code_rows(ws_s)
    for code in zs[0]:
        if code not in rows:
            continue
        for col, z in zip(PERIOD_COLS, zs):
            ws_s.cell(rows[code], col).value = z[code]

    ws_s.cell(6, TOKKI_COL).value = f"業種　　{gaiyo['業種']}"
    ws_s.cell(7, TOKKI_COL).value = f"設立　　{gaiyo['設立日']}"
    for r in TOKKI_ROWS:
        ws_s.cell(r, TOKKI_COL).value = None
    for r, v in zip(TOKKI_ROWS, gaiyo['決算内容']):
        ws_s.cell(r, TOKKI_COL).value = v

    ws_k = wb['企業概要表']
    ws_k.cell(25, 16).value = zs[-1][700]
    ws_k.cell(30, 6).value = gaiyo['設立年']
    ws_k.cell(30, 10).value = gaiyo['設立月']
    ws_k.cell(31, 4).value = gaiyo['沿革']
    ws_k.cell(60, 25).value = gaiyo['特記事項']
    for (r, c), v in zip(((26, 5), (26, 14), (28, 5), (28, 14)),
                         list(gaiyo['取扱品目']) + [None] * 4):
        ws_k.cell(r, c).value = v
    for i, row in enumerate(range(50, 54)):
        ws_k.cell(row, 8).value = round(zs[i][740] / 1000)
        ws_k.cell(row, 14).value = round(zs[i][840] / 1000)
        ws_k.cell(row, 19).value = round(zs[i][870] / 1000)

    ws_h = wb['顧客カルテ']
    for (r, c), v in hyoshi.items():
        ws_h.cell(r, c).value = v
    for r in (20, 21, 22, 23):
        ws_h.cell(r, 37).value = entai
    for i, row in enumerate((28, 29, 30, 31, 32, 33)):
        code = (740, 840, 870, 890, 430, 690)[i]
        for j, col in enumerate((9, 15, 21)):
            ws_h.cell(row, col).value = f'{int(zs[j + 1][code] / 1000):,}'

    ws_g = wb['グループ合併バランス']
    ws_g.cell(36, 14).value = entai
    ws_g.cell(36, 15).value = entai
    ws_g.cell(35, 15).value = hyoshi.get((12, 18))

    wb.save(dst)
    last = zs[-1]
    print(f'{name}')
    print(f'   資産{last[430]:,} ＝ 負債{last[680]:,} ＋ 自己資本{last[690]:,}'
          f'／有利子負債{last[730]:,}')
    print(f'   自己資本比率{last[990]*100:.1f}% 流動比率{last[1000]*100:.1f}% '
          f'償還年数{last[1050]}年 繰越{last[720]:,} 営業利益{last[820]:,}')


