def _uchiwake(head_row, header, rows, goukei_row):
    """T列の内訳ブロックを差し替える。ラベルと4期分の値を入れ、余った行は消す。"""
    _ws.cell(head_row, TOKKI_COL, header)
    r = head_row + 1
    for label, vals in rows:
        _ws.cell(r, TOKKI_COL, label)
        for col, v in zip(PERIOD_COLS_UCHIWAKE, vals):
            _ws.cell(r, col, v)
        r += 1
    # ws.cell(r, c, None) は値を消さない（openpyxlは value=None を「指定なし」と扱う）。
    # .value = None で消す。
    while r < goukei_row:
        _ws.cell(r, TOKKI_COL).value = None
        for col in PERIOD_COLS_UCHIWAKE:
            _ws.cell(r, col).value = None
        r += 1
    _ws.cell(goukei_row, TOKKI_COL, '合計')
    for i, col in enumerate(PERIOD_COLS_UCHIWAKE):
        _ws.cell(goukei_row, col, sum(v[i] for _, v in rows))


PERIOD_COLS_UCHIWAKE = [25, 29, 33, 37]
